import jsPDF from 'jspdf'
import autoTable from 'jspdf-autotable'
import * as XLSX from 'xlsx'
import { getStockStatus } from './inventoryUtils'

const statusLabels = {
  'in-stock': 'In Stock',
  'low-stock': 'Low Stock',
  'out-of-stock': 'Out of Stock',
}

// Colours for the PDF (RGB numbers)
const FOREST = [35, 76, 58]
const PEACH = [208, 159, 92]
const GREY = [120, 129, 120]
const CREAM = [251, 247, 239]
const statusColors = {
  'In Stock': [24, 61, 46],
  'Low Stock': [138, 98, 21],
  'Out of Stock': [155, 59, 51],
}

// Turns real products into plain rows used by both PDF and Excel.
function buildRows(products) {
  return products.map((product) => ({
    name: product.name,
    category: product.category,
    quantity: product.quantity,
    unit: product.unit,
    price: product.price,
    status: statusLabels[getStockStatus(product)],
  }))
}

// "2026-10-31" style date for file names.
function todayForFileName() {
  return new Date().toLocaleDateString('en-CA')
}

// "bizpilot-low-stock-2026-10-31.pdf"
function buildFileName(tabLabel, extension) {
  const slug = tabLabel.toLowerCase().replace(/\s+/g, '-')
  return `bizpilot-${slug}-${todayForFileName()}.${extension}`
}

// Describes the active search / filters, e.g. "Search: milk · Category: Dairy"
function describeFilters({ searchQuery, category, sortOrder }) {
  const parts = []
  if (searchQuery.trim()) parts.push(`Search: "${searchQuery.trim()}"`)
  if (category !== 'all') parts.push(`Category: ${category}`)
  if (sortOrder === 'low-high') parts.push('Sorted by price: low to high')
  if (sortOrder === 'high-low') parts.push('Sorted by price: high to low')
  return parts.length > 0 ? parts.join('  ·  ') : 'None'
}

export function exportToPdf(products, tabLabel, filters) {
  const rows = buildRows(products)
  const doc = new jsPDF({ unit: 'pt', format: 'a4' })
  const pageWidth = doc.internal.pageSize.getWidth()
  const margin = 40

  // --- BizPilot heading (Biz in green, Pilot in peach) ---
  doc.setFont('times', 'bold')
  doc.setFontSize(24)
  doc.setTextColor(...FOREST)
  doc.text('Biz', margin, 56)
  const bizWidth = doc.getTextWidth('Biz')
  doc.setTextColor(...PEACH)
  doc.text('Pilot', margin + bizWidth, 56)

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(9)
  doc.setTextColor(...GREY)
  doc.text('AI Business Assistant', margin, 70)

  // --- Report title and details ---
  doc.setFont('helvetica', 'bold')
  doc.setFontSize(16)
  doc.setTextColor(...FOREST)
  doc.text('Inventory Report', margin, 104)

  const generated = new Date().toLocaleDateString('en-IN', {
    day: 'numeric',
    month: 'long',
    year: 'numeric',
  })

  doc.setFont('helvetica', 'normal')
  doc.setFontSize(10)
  doc.setTextColor(38, 53, 45)
  doc.text(`Stock category: ${tabLabel}`, margin, 124)
  doc.text(`Generated on: ${generated}`, margin, 139)
  doc.text(`Filters applied: ${describeFilters(filters)}`, margin, 154)
  doc.text(`Total products: ${rows.length}`, margin, 169)

  // --- Table ---
  autoTable(doc, {
    startY: 185,
    margin: { left: margin, right: margin },
    head: [['Product Name', 'Category', 'Quantity', 'Unit', 'Selling Price', 'Status']],
    body: rows.map((row) => [
      row.name,
      row.category,
      String(row.quantity),
      row.unit,
      `Rs. ${row.price.toFixed(2)}`,
      row.status,
    ]),
    styles: { font: 'helvetica', fontSize: 10, cellPadding: 6, textColor: [38, 53, 45] },
    headStyles: { fillColor: FOREST, textColor: 255, fontStyle: 'bold' },
    alternateRowStyles: { fillColor: CREAM },
    columnStyles: {
      2: { halign: 'right' },
      4: { halign: 'right' },
    },
    // Colour the status text.
    didParseCell: (data) => {
      if (data.section === 'body' && data.column.index === 5) {
        data.cell.styles.textColor = statusColors[data.cell.raw]
        data.cell.styles.fontStyle = 'bold'
      }
    },
  })

  // --- Page numbers on every page ---
  const pageCount = doc.getNumberOfPages()
  const pageHeight = doc.internal.pageSize.getHeight()
  doc.setFont('helvetica', 'normal')
  doc.setFontSize(9)
  doc.setTextColor(...GREY)
  for (let page = 1; page <= pageCount; page += 1) {
    doc.setPage(page)
    doc.text(`Page ${page} of ${pageCount}`, pageWidth - margin, pageHeight - 20, {
      align: 'right',
    })
    doc.text('Generated by BizPilot', margin, pageHeight - 20)
  }

  doc.save(buildFileName(tabLabel, 'pdf'))
}

export function exportToExcel(products, tabLabel) {
  const rows = buildRows(products)

  // Each key becomes a column heading in the sheet.
  const sheetData = rows.map((row) => ({
    'Product Name': row.name,
    Category: row.category,
    'Available Quantity': row.quantity,
    Unit: row.unit,
    'Selling Price (₹)': row.price,
    'Stock Status': row.status,
  }))

  const worksheet = XLSX.utils.json_to_sheet(sheetData)

  // Column widths
  worksheet['!cols'] = [{ wch: 26 }, { wch: 14 }, { wch: 18 }, { wch: 10 }, { wch: 18 }, { wch: 14 }]

  // Show prices with 2 decimals (column index 4). Row 0 is the heading.
  for (let rowIndex = 1; rowIndex <= rows.length; rowIndex += 1) {
    const cell = worksheet[XLSX.utils.encode_cell({ r: rowIndex, c: 4 })]
    if (cell) cell.z = '#,##0.00'
  }

  const workbook = XLSX.utils.book_new()
  XLSX.utils.book_append_sheet(workbook, worksheet, tabLabel)
  XLSX.writeFile(workbook, buildFileName(tabLabel, 'xlsx'))
}